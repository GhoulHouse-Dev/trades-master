import { z } from "zod";

const navItem = z.object({ label: z.string().min(1), href: z.string().min(1) });
const textBlock = z.object({ title: z.string().min(1), text: z.string().min(1) });
const service = z.object({
  title: z.string().min(1),
  description: z.string().min(1),
  bullets: z.array(z.string().min(1)).optional(),
  cta: z.string().min(1).optional(),
});

export const siteConfigSchema = z.object({
  slug: z.string().min(1).optional(),
  locale: z.string().min(2).optional(),
  trade: z.enum(["lvi", "remontti", "sahko"]),
  company: z.object({
    name: z.string().min(1),
    legalName: z.string().min(1).optional(),
    businessId: z.string().min(1).optional(),
    tagline: z.string().min(1),
    description: z.string().min(1),
    phone: z.string().min(5),
    phoneHref: z.string().startsWith("tel:").optional(),
    email: z.union([z.literal(""), z.string().email()]),
    contactPerson: z.string().optional(),
    contactRole: z.string().optional(),
    streetAddress: z.string().optional(),
    postalCode: z.string().optional(),
    city: z.string().min(1),
    address: z.string().optional(),
    serviceArea: z.array(z.string().min(1)).min(1),
    serviceAreaNote: z.string().optional(),
    foundedYear: z.number().int().min(1800).max(2100).optional(),
    logoText: z.string().min(1).max(8).optional(),
  }),
  seo: z.object({
    siteUrl: z.string().url(),
    title: z.string().min(10),
    description: z.string().min(30),
    locale: z.string().min(2),
    ogTitle: z.string().optional(),
    noindex: z.boolean().optional(),
  }),
  theme: z.object({
    primary: z.string().optional(),
    accent: z.string().min(1),
    accentStrong: z.string().min(1),
    surface: z.string().min(1),
    ink: z.string().min(1),
  }),
  nav: z.array(navItem).optional(),
  ctaLabel: z.string().optional(),
  hero: z.object({
    eyebrow: z.string().min(1),
    badge: z.string().optional(),
    panelLabel: z.string().optional(),
    title: z.string().min(1),
    lead: z.string().min(1),
    primaryCta: z.string().min(1),
    secondaryCta: z.string().min(1),
    highlights: z.array(z.string()),
    facts: z.array(z.object({ value: z.string(), label: z.string() })).optional(),
    priceCard: z.object({
      title: z.string(),
      value: z.string(),
      note: z.string(),
      linkLabel: z.string(),
      linkHref: z.string(),
      prominent: z.boolean().optional(),
      bullets: z.array(z.string()).optional(),
    }).optional(),
  }),
  services: z.array(service).min(1),
  servicesHeading: z.object({ title: z.string(), intro: z.string().optional() }).optional(),
  whyUs: z.array(textBlock).optional(),
  whyUsHeading: z.string().optional(),
  pricing: z.object({
    title: z.string(),
    intro: z.string().optional(),
    rows: z.array(z.object({ label: z.string(), price: z.string() })).min(1),
    footnote: z.string().optional(),
    cta: z.string().optional(),
  }).optional(),
  projects: z.array(z.object({ title: z.string(), location: z.string(), description: z.string(), image: z.string() })),
  testimonials: z.array(z.object({ quote: z.string(), name: z.string(), meta: z.string().optional() })),
  process: z.array(z.object({ title: z.string(), description: z.string() })).min(1),
  processHeading: z.string().optional(),
  faqs: z.array(z.object({ question: z.string(), answer: z.string() })).min(1),
  faqHeading: z.string().optional(),
  trust: z.object({ heading: z.string(), items: z.array(z.string()) }),
  contact: z.object({
    title: z.string().optional(),
    intro: z.string().optional(),
    sideTitle: z.string().optional(),
    personLine: z.string().optional(),
    formTitle: z.string().optional(),
    button: z.string().optional(),
    success: z.string().optional(),
    error: z.string().optional(),
    privacyLine: z.string().optional(),
    serviceOptions: z.array(z.string()).optional(),
    fields: z.object({
      email: z.enum(["hidden", "optional", "required"]).optional(),
      city: z.enum(["hidden", "optional", "required"]).optional(),
    }).optional(),
    placeholders: z.object({
      name: z.string().optional(),
      phone: z.string().optional(),
      email: z.string().optional(),
      city: z.string().optional(),
      message: z.string().optional(),
    }).optional(),
  }).optional(),
  footer: z.object({ links: z.array(navItem).optional(), copyright: z.string().optional() }).optional(),
  privacy: z.object({
    title: z.string(),
    sections: z.array(z.object({ heading: z.string(), text: z.string() })).min(1),
  }).optional(),
  needsConfirmation: z.array(z.string()).optional(),
  socials: z.object({ facebook: z.string().url().optional(), instagram: z.string().url().optional() }).optional(),
});

export type ValidatedSiteConfig = z.infer<typeof siteConfigSchema>;
